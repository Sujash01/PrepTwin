import { forwardRef, type HTMLAttributes } from 'react'
import { cn } from '../../utils/helpers'

interface CardProps extends HTMLAttributes<HTMLDivElement> {
  variant?: 'default' | 'hover' | 'glass'
  padding?: 'none' | 'sm' | 'md' | 'lg'
}

export const Card = forwardRef<HTMLDivElement, CardProps>(
  ({ className, variant = 'default', padding = 'md', children, ...props }, ref) => {
    const variants = {
      default: 'bg-surface-900/50 backdrop-blur-xl border border-surface-700/50 rounded-2xl',
      hover: 'bg-surface-900/50 backdrop-blur-xl border border-surface-700/50 rounded-2xl transition-all duration-300 hover:bg-surface-800/60 hover:border-surface-600/50 hover:shadow-glass-hover hover:-translate-y-1',
      glass: 'bg-surface-900/30 backdrop-blur-xl border border-surface-700/30 rounded-2xl',
    }

    const paddings = {
      none: '',
      sm: 'p-4',
      md: 'p-6',
      lg: 'p-8',
    }

    return (
      <div
        ref={ref}
        className={cn(variants[variant], paddings[padding], className)}
        {...props}
      >
        {children}
      </div>
    )
  }
)

Card.displayName = 'Card'

export const CardHeader = forwardRef<HTMLDivElement, HTMLAttributes<HTMLDivElement>>(
  ({ className, children, ...props }, ref) => (
    <div ref={ref} className={cn('mb-4', className)} {...props}>
      {children}
    </div>
  )
)

CardHeader.displayName = 'CardHeader'

